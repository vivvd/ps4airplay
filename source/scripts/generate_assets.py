#!/usr/bin/env python3
"""Generate original icon, bitmap glyph atlas and embedded diagnostics page.

Needs Pillow only when regenerating. Generated files are checked into the source
archive; building the PS4 executable itself does not require Pillow.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import os
import math
ROOT = Path(__file__).resolve().parents[1]
font_path = os.environ.get('LAB_FONT', '/System/Library/Fonts/Supplemental/Arial.ttf')
font = ImageFont.truetype(font_path, 27)
codes = list(range(32, 127)) + list(range(0x400, 0x460))
bits = bytearray()
for code in codes:
    im = Image.new('L', (32, 36))
    ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=255)
    bits.extend(im.tobytes())
generated = ROOT / 'generated'
generated.mkdir(exist_ok=True)
with (generated / 'font_atlas.h').open('w') as f:
    f.write('/* Original raster glyph atlas generated by generate_assets.py. */\n')
    f.write('static const unsigned char lab_font[] = {\n')
    for start in range(0, len(bits), 32):
        f.write(','.join(str(v) for v in bits[start:start+32]) + ',\n')
    f.write('};\n')
    f.write('static const unsigned char lab_advances[] = {')
    f.write(','.join(str(math.ceil(font.getlength(chr(c)))) for c in codes))
    f.write('};\n')
page = (ROOT / 'assets/diagnostics.html').read_bytes()
with (generated / 'web_page.h').open('w') as f:
    f.write('static const char lab_web_page[] = {\n')
    for start in range(0, len(page), 32):
        f.write(','.join(str(v) for v in page[start:start+32]) + ',\n')
    f.write('0};\n')
im = Image.new('RGB', (512, 512), '#0d1422')
d = ImageDraw.Draw(im)
d.rounded_rectangle((86, 95, 426, 315), radius=24, outline='#73e3ce', width=12)
d.polygon([(256, 243), (191, 343), (321, 343)], fill='#eef3fb')
d.rounded_rectangle((234, 348, 278, 361), radius=5, fill='#eef3fb')
d.text((256, 408), 'RECEIVER LAB', font=ImageFont.truetype(font_path, 34), anchor='mm', fill='#eef3fb')
d.text((256, 452), 'FULL HD TEST 0.13', font=ImageFont.truetype(font_path, 18), anchor='mm', fill='#8fa3be')
im.save(ROOT / 'assets/icon0.png')

