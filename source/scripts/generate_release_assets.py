#!/usr/bin/env python3
"""Regenerate embedded OFL font, release icon and diagnostics HTML (Pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
r=Path(__file__).resolve().parents[1]
font=r/'assets/fonts/NotoSans-Regular.ttf'
def embed(path,name,output,zero=False):
 b=path.read_bytes()
 output.write_text('/* Generated by scripts/generate_release_assets.py */\nstatic const unsigned char '+name+'[] = {\n'+''.join(','.join(str(v) for v in b[i:i+32])+',\n' for i in range(0,len(b),32))+('0' if zero else '')+'};\n')
embed(font,'noto_font',r/'generated/noto_font.h')
# HTTP uses char, not unsigned char.
embed(r/'assets/diagnostics.html','lab_web_page',r/'generated/web_page.h',True)
p=r/'generated/web_page.h';p.write_text(p.read_text().replace('unsigned char lab_web_page','char lab_web_page'))
im=Image.new('RGB',(512,512),'#11141e');d=ImageDraw.Draw(im)
d.rounded_rectangle((94,92,418,298),radius=23,outline='#e6eaf2',width=10)
d.polygon([(256,231),(194,328),(318,328)],fill='#e6eaf2')
d.text((256,398),'PS4 AirPlay',font=ImageFont.truetype(str(font),43),anchor='mm',fill='#f4f5f8')
d.text((256,454),'1.00 · RELEASE CANDIDATE',font=ImageFont.truetype(str(font),17),anchor='mm',fill='#8894aa')
im.save(r/'assets/icon0.png')
